CREATE TABLE ra_ai_export_audit (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  actor_doctor_id BIGINT NOT NULL,
  source VARCHAR(7) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  reference_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  payload_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  scope_fingerprint CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  selection_mode VARCHAR(8) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  requested_items VARCHAR(1024) NOT NULL,
  condition_summary VARCHAR(4096) NOT NULL,
  source_policy_versions VARCHAR(4096) NOT NULL,
  export_policy_version VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  free_start DATE NOT NULL,
  policy_today DATE NOT NULL,
  cohort_n INT NULL,
  cohort_a_n INT NULL,
  cohort_b_n INT NULL,
  created_at_ms BIGINT NOT NULL,
  generation_status VARCHAR(10) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
